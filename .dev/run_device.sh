#!/bin/zsh
# Build the Paseo app as a standalone Release build (JS bundled, no Metro), install it on a paired
# iPhone and launch it. Tracked on the personal yayugu branch; other .dev/ state stays ignored.
#
# Usage: .dev/run_device.sh [--no-build]
#   DEVICE=<udid>      pick the device (default: the first paired iPhone, wired ones first)
#   TEAM=<team id>     signing team (default: XVG97NLJ56)
#   BUNDLE_ID=<id>     bundle id (default: sh.paseo.debug.local, so it does not collide with the
#                      App Store build or the official sh.paseo.debug registration)
set -euo pipefail
repo="${0:A:h}/.."
[[ ! -f "$repo/.dev/expo.env" ]] || source "$repo/.dev/expo.env"
cd "$repo/packages/app"

build=1
[[ "${1:-}" == --no-build ]] && build=0

team=${TEAM:-XVG97NLJ56}
bundle_id=${BUNDLE_ID:-sh.paseo.debug.local}
export PASEO_IOS_BUNDLE_IDENTIFIER="$bundle_id"
derived=ios/build/DerivedDataDevice
app=$derived/Build/Products/Release-iphoneos/PaseoDebug.app

if [[ -z "${DEVICE:-}" ]]; then
  devices=$(mktemp -t devices)
  trap 'rm -f "$devices"' EXIT
  xcrun devicectl list devices --json-output "$devices" >/dev/null
  DEVICE=$(jq -r '
    [.result.devices[]
      | select(.hardwareProperties.reality == "physical"
               and .hardwareProperties.platform == "iOS"
               and .connectionProperties.pairingState == "paired")]
    | sort_by(.connectionProperties.transportType != "wired")
    | .[0].hardwareProperties.udid // empty' "$devices")
  [[ -n "$DEVICE" ]] || { echo "No paired iPhone found." >&2; exit 1; }
fi
echo "Device: $DEVICE  Team: $team  Bundle: $bundle_id"

if (( build )); then
  # ios/ is generated and ignored, so a rebase that bumps the Expo SDK leaves it stale (old
  # deployment target, mismatched pods). Regenerate it whenever the installed Expo version
  # differs from the one that generated it.
  expo_version=$(node -p 'require("expo/package.json").version')
  stamp=ios/.paseo-expo-version
  if [[ ! -d ios/PaseoDebug.xcworkspace || "$(cat "$stamp" 2>/dev/null)" != "$expo_version" ]]; then
    APP_VARIANT=development CI=1 npx expo prebuild --platform ios --clean
    echo "$expo_version" >"$stamp"
  fi
  # Only the app target's id changes; pods' resource bundles keep theirs.
  sed -i '' -E "s/PRODUCT_BUNDLE_IDENTIFIER = sh\.paseo\.debug[^;]*;/PRODUCT_BUNDLE_IDENTIFIER = $bundle_id;/" \
    ios/PaseoDebug.xcodeproj/project.pbxproj
  npm --prefix ../.. run -s build:app-deps

  # npm ci removes sources generated by podspecs, such as expo-sqlite's sqlite3.c/h.
  # Restore them and sync native dependencies even when the workspace already exists.
  (cd ios && APP_VARIANT=development pod install)

  # Xcode 27 rejects the 9.0–13.4 deployment targets some pods still declare. 16.4 is the
  # floor Expo SDK 57 modules require; overriding below it breaks them.
  APP_VARIANT=development xcodebuild -workspace ios/PaseoDebug.xcworkspace -scheme PaseoDebug \
    -configuration Release -destination "id=$DEVICE" -derivedDataPath "$derived" \
    -allowProvisioningUpdates -quiet \
    DEVELOPMENT_TEAM="$team" IPHONEOS_DEPLOYMENT_TARGET=16.4 \
    build
fi

xcrun devicectl device install app --device "$DEVICE" "$app"
xcrun devicectl device process launch --device "$DEVICE" --terminate-existing "$bundle_id"
